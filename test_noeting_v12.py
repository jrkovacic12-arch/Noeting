from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parent
checks=[]
def check(name, condition):
    assert condition, name
    checks.append(name)

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1440,'height':960},device_scale_factor=1)
    page.set_default_timeout(3000)
    errors=[]
    page.on('pageerror', lambda x: errors.append(str(x)))
    page.set_content((ROOT/'noeting_capture_today_prototype.html').read_text(),wait_until='load')
    page.evaluate("""window.__storageMock={};Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>window.__storageMock[k]??null,setItem:(k,v)=>{window.__storageMock[k]=v},removeItem:k=>delete window.__storageMock[k]}}); storageOK=true;""")
    check('Today shows one Tasks panel',page.get_by_role('heading',name='Tasks',exact=True).count()==1 and page.get_by_role('heading',name='My priorities').count()==0)
    check('Only one global Capture control, none in navigation',page.locator('[data-action=open-capture]').count()==1 and page.locator('#nav [data-action=open-capture]').count()==0)
    check('Daily summary replaces stats and duplicate brief',page.locator('.daily-summary').count()==1 and page.locator('.stat').count()==0 and page.get_by_role('heading',name='Daily brief').count()==0)
    check('Prototype controls collapsed by default',page.locator('details.demo-tools').count()==1 and page.locator('details.demo-tools').get_attribute('open') is None)
    check('Add task available on Today',page.get_by_role('button',name='+ Add task').is_visible())
    check('Think panel has no Skip',page.get_by_role('button',name='Skip for today').count()==0 and page.get_by_role('button',name='Skip',exact=True).count()==0)
    page.get_by_role('button',name='Capture',exact=True).first.click()
    check('Capture exposes only Note and Task',page.locator('#capture-form input[name=type]').evaluate_all('(els)=>els.map(x=>x.value).join(",")')=='Note,Task')
    check('General Capture defaults to Note',page.locator('#capture-form input[value=Note]').is_checked())
    check('Capture heading is not duplicated',page.locator('#modal-root .modal-head h2').count()==1 and page.locator('#modal-root .modal-head .eyebrow').count()==0)
    check('Capture cancel redundant control removed',page.locator('#capture-form button').count()==1)
    original='  Maybe constant feeds interrupt independent thinking.  '
    page.locator('#capture-text').fill(original)
    page.get_by_role('button',name='Save & close').click()
    data=page.evaluate('window.noetingPrototype.getSnapshot()')
    check('Note preserves exact original text',data['entries'][0]['text']==original)
    check('Note creates no task',len(data['tasks'])==0)
    check('Capture closes immediately without follow-up',page.locator('#modal-root [role="dialog"]').count()==0)
    page.get_by_role('button',name='+ Add task').click()
    check('Today Add task preselects Task',page.locator('#capture-form input[value=Task]').is_checked())
    page.locator('#capture-text').fill('Pay electricity bill')
    page.get_by_role('button',name='Save & close').click()
    data=page.evaluate('window.noetingPrototype.getSnapshot()')
    check('Direct task capture creates linked Task once',len(data['tasks'])==1 and data['tasks'][0]['entryId']==data['entries'][1]['id'])
    check('Direct task requires no clarification step',data['tasks'][0]['title']=='Pay electricity bill' and page.locator('#modal-root [role="dialog"]').count()==0)
    check('Task has no invented dates or priorities',data['tasks'][0]['dueAt']=='' and data['tasks'][0]['remindAt']=='' and data['tasks'][0]['priority'] is False)
    check('Task immediately appears in Today only once',page.locator('.task-row').filter(has_text='Pay electricity bill').count()==1)
    check('No unassigned due-date placeholders',page.get_by_text('No due date').count()==0)
    page.get_by_role('button',name='Capture',exact=True).first.click()
    page.locator('#capture-form input[value=Task]').check()
    check('Changing capture mode updates label',page.locator('label[for="capture-text"]').inner_text()=='What needs doing?')
    page.locator('#capture-text').fill('Walk for 20 minutes')
    page.get_by_role('button',name='Save & close').click()
    check('General capture can directly add a task',len(page.evaluate('window.noetingPrototype.getSnapshot().tasks'))==2)
    page.get_by_role('button',name='Library',exact=True).click()
    check('Library shows only 3 filters',page.locator('button[data-filter]').all_text_contents()==['All','Note','Task'])
    check('Library does not duplicate global Capture button',page.locator('[data-action=open-capture]').count()==1)
    page.locator('#search').fill('constant feeds')
    check('Library search finds original note',page.locator('.entry-row').count()==1)
    for label, action in [('New task','clarify'),('Reflect','reflect'),('Create','reflect'),('Today note','select-thought')]:
        check('Library has '+label+' action',page.locator('.entry-row button').filter(has_text=label).count()==1 and page.locator('.entry-row button').filter(has_text=label).get_attribute('data-action')==action)
    page.get_by_role('button',name='New task',exact=True).click()
    check('Note-to-task suggestion remains opt-in',page.locator('#task-candidate').is_visible() and len(page.evaluate('window.noetingPrototype.getSnapshot().tasks'))==2)
    page.get_by_role('button',name='Dismiss').click()
    check('Dismissing suggestion adds no task',len(page.evaluate('window.noetingPrototype.getSnapshot().tasks'))==2)
    page.get_by_role('button',name='New task',exact=True).click()
    page.locator('#task-candidate').fill('Investigate feeds')
    page.get_by_role('button',name='Accept task').click()
    data=page.evaluate('window.noetingPrototype.getSnapshot()')
    check('Accept creates one linked task without modifying note',len(data['tasks'])==3 and data['tasks'][-1]['entryId']==data['entries'][0]['id'] and data['entries'][0]['text']==original)
    page.locator('#search').fill('constant feeds')
    page.get_by_role('button',name='Reflect',exact=True).click()
    page.locator('#reflect-text').fill('Not all interruptions are bad.')
    page.get_by_role('button',name='Save reflection').click()
    data=page.evaluate('window.noetingPrototype.getSnapshot()')
    check('Linked reflection retains original text',data['entries'][0]['text']==original and data['entries'][-1]['parentId']==data['entries'][0]['id'])
    page.get_by_role('button',name='Today',exact=True).click()
    page.get_by_role('button',name='Choose a note').click()
    check('Today Choose only lists notes, not Tasks',page.get_by_role('button',name='Select').count()==2)
    page.get_by_role('button',name='Select').first.click()
    check('Think panel remains finite and Skip-free',page.get_by_role('button',name='Reflect').is_visible() and page.get_by_role('button',name='Skip').count()==0)
    check('Today shows renamed Create action',page.get_by_role('button',name='Create',exact=True).is_visible() and page.get_by_role('button',name='Develop into creation').count()==0)
    # Reminder record, not notification delivery
    page.get_by_role('button',name='Edit').first.click()
    page.locator('#edit-task-reminder').fill('2026-10-15T09:00')
    check('Reminder non-delivery is disclosed',page.get_by_text('No notification will fire.',exact=False).is_visible())
    page.get_by_role('button',name='Save task').click()
    check('Reminder is recorded only',page.evaluate('window.noetingPrototype.getSnapshot().tasks[0].remindAt')=='2026-10-15T09:00')
    for n in range(2):
        page.get_by_role('button',name='+ Add task').click()
        page.locator('#capture-text').fill('Extra task '+str(n+1))
        page.get_by_role('button',name='Save & close').click()
    for n in range(3):
        page.locator('[data-action=priority][aria-pressed=false]').first.click()
    check('At most 3 priorities can be selected',sum(x['priority'] for x in page.evaluate('window.noetingPrototype.getSnapshot().tasks'))==3)
    check('Fourth priority is disabled',page.locator('[data-action=priority][aria-pressed=false]').first.is_disabled())
    check('Only one row for each task',page.locator('.task-row').count()==len(page.evaluate('window.noetingPrototype.getSnapshot().tasks.filter(x=>x.status==="Pending")')))
    check('Pinned tasks are sorted first',page.locator('.task-row').evaluate_all('(els)=>els.slice(0,3).every(x=>x.classList.contains("pinned"))'))
    check('Pinned counter shows limit',page.locator('[aria-label="Pinned tasks"]').inner_text()=='3 / 3 pinned')
    page.locator('[data-action=priority][aria-pressed=true]').last.click()
    check('Unpin restores room in priority cap',sum(x['priority'] for x in page.evaluate('window.noetingPrototype.getSnapshot().tasks'))==2 and page.locator('[data-action=priority][aria-pressed=false]').first.is_enabled())
    check('No task appears more than once after unpin',page.locator('.task-row').count()==len(page.evaluate('window.noetingPrototype.getSnapshot().tasks.filter(x=>x.status==="Pending")')))
    page.locator('[data-action=priority][aria-pressed=false]').first.click()
    check('Pin reclaims third slot',sum(x['priority'] for x in page.evaluate('window.noetingPrototype.getSnapshot().tasks'))==3)
    page.get_by_role('button',name='Finish session').click()
    check('Finite exit is still functional',page.get_by_role('heading',name='Enough for today.').is_visible())
    page.get_by_role('button',name='Return to Today').click()
    page.evaluate("""state=initial();load();render()""")
    check('Simulated storage restore retains direct Task',page.evaluate('window.noetingPrototype.getSnapshot().tasks[0].title')=='Pay electricity bill')
    # Legacy data is still displayable, without destructive migration
    page.evaluate("""window.__storageMock[STORAGE_KEY]=JSON.stringify({entries:[{id:'old1',text:'Old idea preserved',type:'Thought',createdAt:'2026-10-11T10:00:00.000Z',parentId:null}],tasks:[],chosenThoughtId:'old1',thinkingSkipped:true});state=initial();load();render()""")
    check('Old Thought remains intact in persisted data',page.evaluate('window.noetingPrototype.getSnapshot().entries[0].type')=='Thought')
    check('Old Thought displays as Note',page.get_by_text('Old idea preserved').is_visible() and page.get_by_role('button',name='Skip for today').count()==0)
    page.get_by_role('button',name='Library',exact=True).click()
    page.get_by_role('button',name='Note',exact=True).click()
    page.locator('#search').fill('Old idea')
    check('Legacy Thought can be found in Note filter',page.locator('.entry-row').count()==1)
    check('No browser exceptions',not errors)
    page.evaluate('window.noetingPrototype.reset()')
    page.locator('details.demo-tools summary').click()
    page.get_by_role('button',name='Load fictional test examples').click()
    page.locator('.task-row').last.locator('[data-action=priority]').click()
    check('Pinned task moves to top after loading example data',page.locator('.task-row').first.locator('.task-title').inner_text()=='Review meeting notes')
    page.locator('details.demo-tools summary').click()
    check('Demo controls hidden after collapsing',page.locator('details.demo-tools').get_attribute('open') is None)
    page.screenshot(path=str(ROOT/'noeting_v12_desktop.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(ROOT/'noeting_v12_mobile.png'),full_page=True)
    browser.close()

print('PASS:',len(checks),'simulated Chromium checks')
for item in checks:print(' -',item)
